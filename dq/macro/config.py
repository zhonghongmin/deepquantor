def _validate_tables() -> None:
    """导入期自检：36 格完备、资产行合计=100、枚举合法。违例直接抛错（fail fast）。"""
    cells = set(EQUITY_CENTER)
    expect = {(r, m) for r in REGIMES for m in MC_ENUM}
    if cells != expect:
        raise RuntimeError(f"36 格基准带不完备：缺 {expect - cells}，多 {cells - expect}")
    if set(ASSET_ALLOC_BASE) != expect:
        raise RuntimeError("ASSET_ALLOC_BASE 与 36 格不一致")
    for key, alloc in ASSET_ALLOC_BASE.items():
        total = EQUITY_CENTER[key] + sum(alloc.values())
        if abs(total - 100.0) > 1e-9:
            raise RuntimeError(f"资产行合计≠100：{key} = {total}")
    for m, c in MC_STATES:
        if m not in (-1, 0, 1) or c not in (-1, 0, 1):
            raise RuntimeError("九态键非法")
    if len(MC_ENUM) != 9:
        raise RuntimeError("货币信用态必须恰 9 个")
    for r in REGIMES:
        if CLOCK_NEXT[r] not in REGIMES or CLOCK_NEXT[r] == r:
            raise RuntimeError(f"周期时钟非法：{r}")
    s = sum(FACTOR_WEIGHTS.values())
    if abs(s - 1.0) > 1e-9 or any(w > FACTOR_WEIGHT_CAP for w in FACTOR_WEIGHTS.values()):
        raise RuntimeError("因子权重非法：Σw=1 且单组 ≤ 0.40")


_validate_tables()
